/**
 * Stable reference timestamp for mock data.
 * Rounded down to the nearest hour so SSR and client hydration always
 * produce the same values — Date.now() in module-scope object literals
 * would otherwise differ between server render and client re-render.
 */
const REF = Math.floor(Date.now() / 3_600_000) * 3_600_000;
const REF_UTC = new Date(REF).toUTCString();

/** Helper: produce an ISO string offset from REF by the given ms. */
function ago(ms: number): string {
  return new Date(REF - ms).toISOString();
}

